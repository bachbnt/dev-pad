//  Represents a single entry in the clipboard history, plus the pure
//  ordering / dedup / privacy rules (`ClipboardHistory`) that
//  ClipboardManager applies. Kept free of pasteboard and disk access so
//  the rules can be unit-tested.
//

import Foundation
import AppKit

struct ClipboardItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable {
        case text
        case image
    }

    let id: UUID
    let kind: Kind
    let text: String?         // populated when kind == .text
    let imageData: Data?      // PNG bytes, populated when kind == .image
    /// When the entry was last copied. Re-copying an existing entry bumps this
    /// (rather than adding a duplicate) so recency sorting keeps it on top.
    var createdAt: Date
    var pinned: Bool

    init(id: UUID = UUID(),
         kind: Kind,
         text: String? = nil,
         imageData: Data? = nil,
         createdAt: Date = Date(),
         pinned: Bool = false) {
        self.id = id
        self.kind = kind
        self.text = text
        self.imageData = imageData
        self.createdAt = createdAt
        self.pinned = pinned
    }

    // MARK: - Convenience

    /// Short preview suitable for menu/list rows.
    var preview: String {
        switch kind {
        case .text:
            let raw = text ?? ""
            let stripped = raw.replacingOccurrences(of: "\n", with: " ")
                .replacingOccurrences(of: "\t", with: " ")
                .trimmingCharacters(in: .whitespaces)
            if stripped.count > 80 {
                return String(stripped.prefix(80)) + "…"
            }
            return stripped.isEmpty ? "(empty)" : stripped
        case .image:
            if let data = imageData,
               let img = NSImage(data: data) {
                let w = Int(img.size.width.rounded())
                let h = Int(img.size.height.rounded())
                let kb = max(1, data.count / 1024)
                return "🖼 Image — \(w)×\(h), \(kb) KB"
            }
            return "🖼 Image"
        }
    }

    /// Returns an NSImage suitable for displaying a thumbnail.
    var nsImage: NSImage? {
        guard kind == .image, let data = imageData else { return nil }
        return NSImage(data: data)
    }

    /// Hash used to deduplicate items: identical text or identical bytes.
    var dedupKey: String {
        switch kind {
        case .text:
            return "T:" + (text ?? "")
        case .image:
            // Use byte length + first/last bytes as a cheap fingerprint.
            guard let d = imageData, !d.isEmpty else { return "I:empty" }
            let head = d.prefix(16).map { String(format: "%02x", $0) }.joined()
            let tail = d.suffix(16).map { String(format: "%02x", $0) }.joined()
            return "I:\(d.count):\(head):\(tail)"
        }
    }
}

// MARK: - History rules

/// Pure rules for the clipboard list: privacy filtering, dedup/bump and the
/// pinned-first / newest-first ordering with a cap on unpinned entries.
enum ClipboardHistory {

    /// Pasteboard types that apps (password managers, Keychain, sync tools)
    /// use to say "do not record this" — see nspasteboard.org. Anything
    /// carrying one of these must never reach the history or the disk.
    static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType"
    ]

    /// True when the pasteboard advertises any type that opts out of history.
    static func shouldSkip(pasteboardTypes: [String]) -> Bool {
        pasteboardTypes.contains { privateTypes.contains($0) }
    }

    /// Pinned items first, then newest first; unpinned items beyond
    /// `maxItems` are dropped. Pinned items are never evicted.
    static func sortAndCap(_ items: [ClipboardItem], maxItems: Int) -> [ClipboardItem] {
        let sorted = items.sorted { a, b in
            if a.pinned != b.pinned { return a.pinned && !b.pinned }
            return a.createdAt > b.createdAt
        }
        var unpinnedCount = 0
        var result: [ClipboardItem] = []
        for item in sorted {
            if item.pinned {
                result.append(item)
            } else if unpinnedCount < maxItems {
                result.append(item)
                unpinnedCount += 1
            }
        }
        return result
    }

    /// Marks the item as just used. Recency is `createdAt`, so the bump has
    /// to change that — moving the array element alone would be undone by
    /// the next `sortAndCap`.
    static func bumped(_ items: [ClipboardItem], id: UUID, now: Date = Date(), maxItems: Int) -> [ClipboardItem] {
        guard let idx = items.firstIndex(where: { $0.id == id }) else { return items }
        var copy = items
        copy[idx].createdAt = now
        return sortAndCap(copy, maxItems: maxItems)
    }

    /// Adds a freshly copied candidate. Returns `nil` when nothing changes
    /// (the newest entry already has identical content). If identical content
    /// exists deeper in the list it is bumped instead of duplicated.
    static func inserting(_ candidate: ClipboardItem, into items: [ClipboardItem], now: Date = Date(), maxItems: Int) -> [ClipboardItem]? {
        let key = candidate.dedupKey
        if let first = items.first, first.dedupKey == key { return nil }
        if let existing = items.first(where: { $0.dedupKey == key }) {
            return bumped(items, id: existing.id, now: now, maxItems: maxItems)
        }
        var copy = items
        copy.insert(candidate, at: 0)
        return sortAndCap(copy, maxItems: maxItems)
    }
}
