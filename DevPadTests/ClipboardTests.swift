import XCTest

final class ClipboardHistoryTests: XCTestCase {

    private let t0 = Date(timeIntervalSince1970: 1_000_000)

    private func text(_ s: String, age: TimeInterval, pinned: Bool = false) -> ClipboardItem {
        ClipboardItem(kind: .text, text: s, createdAt: t0.addingTimeInterval(-age), pinned: pinned)
    }

    func testNewestFirstAndPinnedOnTop() {
        let items = [text("old", age: 300), text("pinned-old", age: 900, pinned: true), text("new", age: 10)]
        let sorted = ClipboardHistory.sortAndCap(items, maxItems: 20)
        XCTAssertEqual(sorted.compactMap(\.text), ["pinned-old", "new", "old"])
    }

    func testCapDropsOldestUnpinnedButNeverPinned() {
        var items = (0..<5).map { text("u\($0)", age: Double($0)) }
        items.append(text("pin", age: 5_000, pinned: true))
        let capped = ClipboardHistory.sortAndCap(items, maxItems: 2)
        XCTAssertEqual(capped.compactMap(\.text), ["pin", "u0", "u1"])
    }

    /// Regression: bumping used to move the element to index 0 and then the
    /// re-sort by `createdAt` put it straight back.
    func testBumpMovesItemToTopAndSurvivesResort() {
        let items = [text("c", age: 10), text("b", age: 20), text("a", age: 30)]
        let target = items[2]
        let bumped = ClipboardHistory.bumped(items, id: target.id, now: t0, maxItems: 20)
        XCTAssertEqual(bumped.compactMap(\.text), ["a", "c", "b"])
        // Sorting again (as togglePin / load do) must keep that order.
        XCTAssertEqual(ClipboardHistory.sortAndCap(bumped, maxItems: 20).compactMap(\.text), ["a", "c", "b"])
    }

    func testBumpOfUnknownIdIsNoOp() {
        let items = [text("a", age: 1)]
        XCTAssertEqual(ClipboardHistory.bumped(items, id: UUID(), maxItems: 20), items)
    }

    func testInsertingDuplicateOfNewestChangesNothing() {
        let items = [text("same", age: 5), text("other", age: 50)]
        XCTAssertNil(ClipboardHistory.inserting(ClipboardItem(kind: .text, text: "same"), into: items, now: t0, maxItems: 20))
    }

    func testInsertingOlderDuplicateBumpsInsteadOfDuplicating() {
        let items = [text("new", age: 5), text("dup", age: 50)]
        let result = ClipboardHistory.inserting(ClipboardItem(kind: .text, text: "dup"), into: items, now: t0, maxItems: 20)
        XCTAssertEqual(result?.compactMap(\.text), ["dup", "new"])
    }

    func testInsertingNewItemGoesOnTopAndRespectsCap() {
        let items = (0..<3).map { text("u\($0)", age: Double($0 + 1)) }
        let result = ClipboardHistory.inserting(ClipboardItem(kind: .text, text: "fresh", createdAt: t0), into: items, now: t0, maxItems: 3)
        XCTAssertEqual(result?.compactMap(\.text), ["fresh", "u0", "u1"])
    }

    func testImageDedupUsesContent() {
        let a = ClipboardItem(kind: .image, imageData: Data([1, 2, 3, 4]))
        let b = ClipboardItem(kind: .image, imageData: Data([1, 2, 3, 4]))
        let c = ClipboardItem(kind: .image, imageData: Data([9, 9, 9, 9]))
        XCTAssertEqual(a.dedupKey, b.dedupKey)
        XCTAssertNotEqual(a.dedupKey, c.dedupKey)
    }

    // MARK: - Privacy

    func testConcealedAndTransientTypesAreSkipped() {
        XCTAssertTrue(ClipboardHistory.shouldSkip(pasteboardTypes: ["public.utf8-plain-text", "org.nspasteboard.ConcealedType"]))
        XCTAssertTrue(ClipboardHistory.shouldSkip(pasteboardTypes: ["org.nspasteboard.TransientType"]))
        XCTAssertTrue(ClipboardHistory.shouldSkip(pasteboardTypes: ["org.nspasteboard.AutoGeneratedType"]))
        XCTAssertFalse(ClipboardHistory.shouldSkip(pasteboardTypes: ["public.utf8-plain-text", "public.rtf"]))
        XCTAssertFalse(ClipboardHistory.shouldSkip(pasteboardTypes: []))
    }
}

final class ClipboardStoreTests: XCTestCase {

    private var suiteName = ""
    private var defaults: UserDefaults!
    private var directory: URL!

    override func setUpWithError() throws {
        suiteName = "DevPadTests.\(UUID().uuidString)"
        defaults = try XCTUnwrap(UserDefaults(suiteName: suiteName))
        directory = FileManager.default.temporaryDirectory
            .appendingPathComponent("DevPadTests-\(UUID().uuidString)", isDirectory: true)
    }

    override func tearDown() {
        defaults?.removePersistentDomain(forName: suiteName)
        if let directory { try? FileManager.default.removeItem(at: directory) }
    }

    private func makeStore() -> ClipboardStore {
        ClipboardStore(defaults: defaults, key: "history", imageDirectory: directory)
    }

    func testRoundTripKeepsTextImageAndPinState() throws {
        let png = Data((0..<2_000).map { UInt8($0 % 251) })
        let items = [
            ClipboardItem(kind: .text, text: "hello", createdAt: Date(timeIntervalSince1970: 100), pinned: true),
            ClipboardItem(kind: .image, imageData: png, createdAt: Date(timeIntervalSince1970: 200))
        ]
        makeStore().write(items)

        let loaded = makeStore().read()
        XCTAssertFalse(loaded.needsMigration)
        XCTAssertEqual(loaded.items.count, 2)
        XCTAssertEqual(loaded.items[0].text, "hello")
        XCTAssertTrue(loaded.items[0].pinned)
        XCTAssertEqual(loaded.items[1].imageData, png)
        XCTAssertEqual(loaded.items[1].id, items[1].id)
        XCTAssertEqual(loaded.items[1].createdAt, items[1].createdAt)
    }

    func testImageBytesAreNotStoredInUserDefaults() throws {
        let png = Data(repeating: 0xAB, count: 500_000)
        makeStore().write([ClipboardItem(kind: .image, imageData: png)])
        let blob = try XCTUnwrap(defaults.data(forKey: "history"))
        XCTAssertLessThan(blob.count, 2_000, "plist must hold a file reference, not the image")
        let files = try FileManager.default.contentsOfDirectory(atPath: directory.path)
        XCTAssertEqual(files.count, 1)
    }

    func testRemovedItemsDeleteTheirImageFiles() throws {
        let keep = ClipboardItem(kind: .image, imageData: Data([1, 2, 3]))
        let drop = ClipboardItem(kind: .image, imageData: Data([4, 5, 6]))
        let store = makeStore()
        store.write([keep, drop])
        store.write([keep])
        let files = try FileManager.default.contentsOfDirectory(atPath: directory.path)
        XCTAssertEqual(files, ["\(keep.id.uuidString).png"])
    }

    func testItemWhoseImageFileDisappearedIsDropped() throws {
        let item = ClipboardItem(kind: .image, imageData: Data([1, 2, 3]))
        let note = ClipboardItem(kind: .text, text: "still here")
        makeStore().write([item, note])
        try FileManager.default.removeItem(at: directory.appendingPathComponent("\(item.id.uuidString).png"))
        XCTAssertEqual(makeStore().read().items.compactMap(\.text), ["still here"])
    }

    /// v1 history stored PNG bytes inline in the UserDefaults JSON.
    func testLegacyInlineImagesAreReadAndFlaggedForMigration() throws {
        struct Legacy: Codable {
            let id: UUID
            let kind: ClipboardItem.Kind
            let text: String?
            let imageData: Data?
            let createdAt: Date
            var pinned: Bool
        }
        let png = Data([7, 7, 7, 7])
        let legacy = [Legacy(id: UUID(), kind: .image, text: nil, imageData: png,
                             createdAt: Date(timeIntervalSince1970: 5), pinned: false)]
        defaults.set(try JSONEncoder().encode(legacy), forKey: "history")

        let store = makeStore()
        let loaded = store.read()
        XCTAssertTrue(loaded.needsMigration)
        XCTAssertEqual(loaded.items.first?.imageData, png)

        store.write(loaded.items)
        let again = makeStore().read()
        XCTAssertFalse(again.needsMigration)
        XCTAssertEqual(again.items.first?.imageData, png)
    }

    func testCorruptDataReadsAsEmpty() {
        defaults.set(Data("not json".utf8), forKey: "history")
        XCTAssertTrue(makeStore().read().items.isEmpty)
    }
}
